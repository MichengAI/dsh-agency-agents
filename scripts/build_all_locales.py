def to_ts_literal(d):
    lines = []
    for k in sorted(d.keys()):
        v = d[k]
        v_escaped = v.replace('\\', '\\\\').replace("'", "\\'").replace('\n', '\\n')
        lines.append(f"  '{k}': '{v_escaped}',")
    return '{\n' + '\n'.join(lines) + '\n}'

