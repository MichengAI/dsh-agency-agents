import { test, expect } from '@playwright/test'

test('英文设置页与专家团详情、编辑表单没有中文界面残留', async ({ page }) => {
  await page.goto('/?teams&settings&lang=en')
  await page.locator('.ant-segmented-item').filter({ has: page.getByRole('radio', { name: 'Expert teams', exact: true }) }).click()
  const cards = page.getByTestId('team-card')
  await expect(cards).toHaveCount(5)
  await expect(cards.first()).toContainText('Product Review Team')
  await expect(page.locator('main')).not.toContainText(/[\u3400-\u9fff]/u)
  await page.screenshot({ path: 'test-results/teams-english.png' })
  await cards.first().getByRole('button', { name: 'View details' }).click()
  await page.getByRole('button', { name: 'View coordinator prompt' }).click()
  await expect(page.getByRole('dialog')).not.toContainText(/[\u3400-\u9fff]/u)
  await page.screenshot({ path: 'test-results/team-details-english.png' })
  await page.getByRole('button', { name: 'Copy and customize' }).click()
  await expect(page.getByRole('dialog')).not.toContainText(/[\u3400-\u9fff]/u)
  await expect(page.getByLabel('Coordinator prompt text')).not.toHaveValue(/[\u3400-\u9fff]/u)
  await page.getByLabel('Team name', { exact: true }).fill('我的自定义名称')
  await page.evaluate(() => (window as unknown as { teamFixtureLocale(locale: string): void }).teamFixtureLocale('zh'))
  await expect(page.getByLabel('团队名称', { exact: true })).toHaveValue('我的自定义名称')
  await expect(page.getByRole('heading', { name: '主理人提示词', exact: true })).toBeVisible()
  await page.evaluate(() => (window as unknown as { teamFixtureLocale(locale: string): void }).teamFixtureLocale('en'))
  await expect(page.getByLabel('Team name', { exact: true })).toHaveValue('我的自定义名称')
})

for (const theme of ['dark', 'light']) test(`${theme}：分类菜单和启用开关使用宿主角色`, async ({ page }) => {
  await page.goto(`/?teams&settings&theme=${theme}`)
  await page.locator('#aag-filter-source').click()
  await expect(page.getByRole('option').first()).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('switch').first()).toBeVisible()
  await page.screenshot({ path: `test-results/official-controls-${theme}.png` })
})

test('聊天团队入口和异步确认使用英文词条与主题弹窗', async ({ page }) => {
  await page.goto('/?teams&menu&lang=en')
  await page.locator('.aag-btn').click()
  await page.locator('.ant-segmented-item').filter({ has: page.getByRole('radio', { name: 'Expert teams', exact: true }) }).click()
  await page.getByRole('textbox', { name: 'Search teams', exact: true }).fill('Product')
  await expect(page.locator('.agt-compact')).toContainText('Product Review Team')
  await expect(page.locator('.agt-compact')).not.toContainText(/[\u3400-\u9fff]/u)
  await page.goto('/?teams&settings&lang=en')
  await page.evaluate(() => { void (window as unknown as { teamFixtureConfirm(): Promise<boolean> }).teamFixtureConfirm() })
  await expect(page.getByRole('dialog', { name: 'Confirm team selection' })).toBeVisible()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
